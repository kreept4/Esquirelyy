/* ⚠ THERE IS NO generateStaticParams HERE, AND IT MUST NOT BE ADDED BACK.
 *
 * Prerendering the twenty one Tier 1 slugs looks free: they never read a
 * cookie, so they could be flat HTML. It was tried and it broke every OTHER
 * profile in production. With generateStaticParams present, Next's default for
 * a param outside the list is to render it statically on demand and cache it,
 * and a static render cannot read cookies. Every gated profile answered 500
 * with digest DYNAMIC_SERVER_USAGE.
 *
 * `await connection()` does not rescue it either. It signals that a render
 * needs a request, but the render Next has already committed to here is a
 * prerender, so the signal is an error rather than a switch.
 *
 * The route is therefore dynamic for everybody. That is a real cost paid for
 * correctness, and a small one: these pages are server rendered per request
 * rather than served from cache, which Google indexes exactly the same way.
 * Getting both would mean Partial Prerendering, or serving gated addresses
 * from an authenticated route instead of the page. Either is a bigger change
 * than a fast TTFB on twenty one pages is worth today.
 */

/**
 * Per-firm metadata, which this page never had.
 *
 * Every profile shared the site-wide title, so fifty-nine pages went out
 * announcing themselves as "Esquirely | Nigeria's Legal Career Platform". A
 * search result for a firm's name has to say the firm's name, and a link
 * pasted into WhatsApp has to preview as that firm rather than as the site.
 *
 * EVERY PROFILE IS NOW INDEXED, gated ones included. See isIndexable for the
 * argument. What that changes here is the description, and the change matters
 * more than the robots line does: for a gated firm this string is now the
 * snippet under a live search result, and it used to end "Sign in to see the
 * full record." A snippet that describes the page's paywall rather than the
 * firm is the one thing that would make indexing these pages a mistake. Both
 * branches now describe the firm; they differ only in whether they promise the
 * application address, which is the one thing a gated page cannot deliver.
 */
export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>
}): Promise<Metadata> {
  const { slug } = await params
  const firm = ALL_FIRMS.find(f => f.slug === slug)
  if (!firm) return { title: 'Firm not found' }

  const cities = firm.offices.map(o => o.city)
  const where = [...new Set(cities)].join(', ')
  const open = isPubliclyReadable(firm)

  return {
    title: firm.name,
    description: open
      ? `${firm.name}: offices, practice areas and how to apply. ${firm.description}`.slice(0, 300)
      : `${firm.name}: ${where ? `offices in ${where}, ` : ''}practice areas and independent rankings. ${firm.description}`.slice(0, 300),
    alternates: { canonical: `/firms/${firm.slug}` },
    /* Points at this route's OWN card, generated by the sibling
       opengraph-image.tsx, not the site default. That file is what makes a
       profile pasted into a group chat preview as the firm rather than as
       Esquirely, which is the whole reason the per-firm card exists. */
    openGraph: openGraph({
      path: `/firms/${firm.slug}`,
      title: `${firm.name} | Esquirely`,
      description: firm.description,
      image: `/firms/${firm.slug}/opengraph-image`,
      type: 'profile',
    }),
    ...(isIndexable(firm) ? {} : { robots: { index: false, follow: true } }),
  }
}

/** Firm mark for the profile header.
 *
 *  This carried its own copy of the storage URL and keyed off `logoFile`
 *  directly, which broke in two ways. Firms whose art was pulled from their own
 *  site have a null `logoFile` and so rendered nothing at all here, even with a
 *  perfectly good PNG in /public. And every other firm was served the untrimmed
 *  bucket original rather than the trimmed art the rest of the site uses, so
 *  this page sized its logos unlike the directory and the ticker.
 *
 *  Going through firmLogo() and LogoFrame fixes both, and means the three
 *  surfaces stay in step from here. */
function FirmAvatar({ firm }: { firm: Firm }) {
  const url = firmLogo(firm)

  if (!url) {
    /* Matches the directory's quiet placeholder rather than a solid ink block.
     * At this size the filled version was the heaviest thing on the page,
     * outweighing the firm's own name beside it. */
    return (
      <span className="firm-monogram firm-monogram-lg">
        <span className="grotesk-bold">{getMonogram(firm.name)}</span>
      </span>
    )
  }

  return <LogoFrame src={url} alt={firm.name} capHeight={3} maxWidth={9} plate />
}

